adminProductsRouter.post("/api/admin/sections", requireAdmin, async (req, res) => {
  try {
    const { name, aisleId, aisleName, aisleCode } = req.body as {
      name?: string;
      aisleId?: number;
      aisleName?: string;
      aisleCode?: string;
    };
    if (!name || typeof name !== "string" || !name.trim()) {
      res.status(400).json({ error: "Section name is required" });
      return;
    }
    const normalizedSectionName = name.trim();
    const existingSectionByName = await prisma.section.findFirst({
      where: {
        name: {
          equals: normalizedSectionName,
          mode: "insensitive",
        },
      },
      select: { id: true },
    });
    if (existingSectionByName) {
      res.status(409).json({ error: "Section name already exists" });
      return;
    }

    let parsedAisleId: number;
    const explicitAisleId = Number(aisleId);
    if (!Number.isNaN(explicitAisleId)) {
      const aisle = await prisma.aisle.findUnique({
        where: { id: explicitAisleId },
        select: { id: true },
      });
      if (!aisle) {
        res.status(400).json({ error: "Aisle does not exist" });
        return;
      }
      parsedAisleId = explicitAisleId;
    } else {
      const fallbackAisleName =
        aisleName && aisleName.trim() ? aisleName.trim() : "Frikopplad gång";
      const fallbackAisleCode =
        aisleCode && aisleCode.trim() ? aisleCode.trim() : "FREE";
      const existingAisle = await prisma.aisle.findFirst({
        where: { code: fallbackAisleCode },
        select: { id: true },
      });
      if (existingAisle) {
        parsedAisleId = existingAisle.id;
      } else {
        const createdAisle = await prisma.aisle.create({
          data: {
            name: fallbackAisleName,
            code: fallbackAisleCode,
          },
          select: { id: true },
        });
        parsedAisleId = createdAisle.id;
      }
    }

    const section = await prisma.section.create({
      data: {
        name: normalizedSectionName,
        aisleId: parsedAisleId,
      },
      include: {
        aisle: {
          select: { id: true, name: true, code: true },
        },
      },
    });

    res.status(201).json(section);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: "Internal server error" });
  }
});

