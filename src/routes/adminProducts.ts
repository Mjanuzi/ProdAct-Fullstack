adminProductsRouter.post("/api/admin/products", requireAdmin, async (req, res) => {
  try {
    const { ean, shelfId, aisleName, sectionName, shelfLabel, position } = req.body as {
      ean?: string;
      shelfId?: number;
      aisleName?: string;
      sectionName?: string;
      shelfLabel?: string;
      position?: number;
    };

    if (!ean || typeof ean !== "string" || !ean.trim()) {
      res.status(400).json({ error: "EAN is required" });
      return;
    }

    const normalizedEan = ean.trim().replace(/\s/g, "");
    if (normalizedEan.length < 8) {
      res.status(400).json({ error: "Invalid EAN" });
      return;
    }

    const existing = await prisma.product.findUnique({
      where: { ean: normalizedEan },
    });
    if (existing) {
      res.status(409).json({
        error: "Product already exists",
        productId: existing.id,
      });
      return;
    }

    const offProduct = await fetchProductByEan(normalizedEan);

    if (!offProduct) {
      res.status(404).json({
        error:
          "Could not find product in Open Food Facts, please check the EAN",
      });
      return;
    }

    const name = offProduct.name;
    const brand = offProduct.brand;
    const description = offProduct.description;
    const categoryName = offProduct.categoryName;

    let category = await prisma.category.findFirst({
      where: { name: categoryName },
    });
    if (!category) {
      category = await prisma.category.create({
        data: { name: categoryName },
      });
    }

    if (shelfId != null) {
      if (!Number.isInteger(shelfId)) {
        res.status(400).json({ error: "Invalid shelfId" });
        return;
      }
      const shelf = await prisma.shelf.findUnique({
        where: { id: shelfId },
        select: { id: true },
      });
      if (!shelf) {
        res.status(400).json({
          error: "Shelf does not exist",
          missingShelfId: shelfId,
        });
        return;
      }
    }

    const product = await prisma.$transaction(async (tx) => {
      const created = await tx.product.create({
        data: {
          ean: normalizedEan,
          openFoodFactsId: offProduct.openFoodFactsId,
          name,
          brand,
          description,
          imageUrl: offProduct.imageUrl || null,
          categoryId: category.id,
        },
      });

      if (
        shelfId != null ||
        (aisleName && aisleName.trim()) ||
        (sectionName && sectionName.trim()) ||
        (shelfLabel && shelfLabel.trim())
      ) {
        await tx.productLocation.create({
          data: {
            productId: created.id,
            shelfId: shelfId ?? null,
            aisleName: aisleName?.trim() || null,
            sectionName: sectionName?.trim() || null,
            shelfLabel: shelfLabel?.trim() || null,
            position: typeof position === "number" ? position : null,
          },
        });
      }

      return created;
    });

    const productWithLocation = await prisma.product.findUnique({
      where: { id: product.id },
      include: {
        category: true,
        locations: {
          include: {
            shelf: {
              include: {
                section: { include: { aisle: true } },
              },
            },
          },
        },
      },
    });

    res.status(201).json(productWithLocation);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: "Internal server error" });
  }
});

adminProductsRouter.put("/api/admin/products/:id", requireAdmin, async (req, res) => {
  try {
    const id = Number(req.params.id);
    if (Number.isNaN(id)) {
      res.status(400).json({ error: "Invalid id" });
      return;
    }

    const { name, brand, description, categoryId } = req.body as {
      name?: string;
      brand?: string;
      description?: string;
      categoryId?: number;
    };

    const data: Prisma.ProductUpdateInput = {};

    if (typeof name === "string" && name.trim()) {
      data.name = name.trim();
    }
    if (typeof brand === "string") {
      data.brand = brand.trim();
    }
    if (typeof description === "string") {
      data.description = description.trim();
    }

    if (categoryId != null) {
      const catId = Number(categoryId);
      if (Number.isNaN(catId)) {
        res.status(400).json({ error: "Invalid categoryId" });
        return;
      }
      const category = await prisma.category.findUnique({
        where: { id: catId },
      });
      if (!category) {
        res.status(400).json({ error: "Category not found" });
        return;
      }
      data.category = { connect: { id: category.id } };
    }

    if (Object.keys(data).length === 0) {
      res.status(400).json({ error: "No fields to update" });
      return;
    }

    const updated = await prisma.product.update({
      where: { id },
      data,
      include: {
        category: true,
        locations: {
          include: {
            shelf: {
              include: {
                section: { include: { aisle: true } },
              },
            },
          },
        },
      },
    });

    res.json(updated);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: "Internal server error" });
  }
});

