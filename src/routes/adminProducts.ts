adminProductsRouter.post("/api/admin/aisles", requireAdmin, async (req, res) => {
  try {
    const { name, code } = req.body as { name?: string; code?: string };
    if (!name || typeof name !== "string" || !name.trim()) {
      res.status(400).json({ error: "Aisle name is required" });
      return;
    }
    const normalizedName = name.trim();
    const existingByName = await prisma.aisle.findFirst({
      where: {
        name: {
          equals: normalizedName,
          mode: "insensitive",
        },
      },
      select: { id: true },
    });
    if (existingByName) {
      res.status(409).json({ error: "Aisle name already exists" });
      return;
    }

    const baseCode =
      (typeof code === "string" && code.trim()
        ? code.trim()
        : normalizedName
            .toUpperCase()
            .replace(/\s+/g, "-")
            .replace(/[^A-Z0-9-]/g, "")
            .slice(0, 12)) || "AISLE";
    let normalizedCode = baseCode;
    let suffix = 2;
    // Ensure unique code even when autogenerated.
    while (true) {
      const existing = await prisma.aisle.findFirst({
        where: { code: normalizedCode },
        select: { id: true },
      });
      if (!existing) break;
      normalizedCode = `${baseCode}-${suffix}`;
      suffix += 1;
    }

    const aisle = await prisma.aisle.create({
      data: {
        name: normalizedName,
        code: normalizedCode,
      },
      select: { id: true, name: true, code: true },
    });

    res.status(201).json(aisle);
  } catch (err) {
    console.error(err);
    res.status(500).json({ error: "Internal server error" });
  }
});

